def is_name_label(en, th):
    """True เมื่อคู่นี้เป็น **ป้ายชื่อเฉพาะ** ไม่ใช่ประโยค — ด่านที่ตรวจสำนวนควรข้าม"""
    if not isinstance(en, str) or not isinstance(th, str):
        return False
    en, th = en.strip(), th.strip()
    if not en or not th:
        return False
    # EN เป็นชื่อเฉพาะได้สองรูป:
    #   1. คำเดียวล้วนตัวอักษร (Hatanaka)
    #   2. ชื่อเต็มสองถึงสามคำที่ขึ้นต้นด้วยตัวใหญ่ทุกคำ (Otake Michihiko) — ตารางการ์ดไทชิ
    #      มีชื่อเต็มหลายร้อยใบ และไทยที่ลงท้ายด้วย "โคะ/นาคะ" ตกด่าน G/M เป็นเท็จทุกใบ
    #      (เจอ 2 ก.ย. 2026 · ก้อน 071)
    # คำสามัญอังกฤษที่ทำให้วลีนั้นเป็น "ชื่อกลุ่ม/ชื่อสิ่งของ" ไม่ใช่ชื่อบุคคล
    COMMON = {"group", "party", "clan", "family", "house", "squad", "corps", "guild",
              "shop", "store", "team", "gang", "school", "temple", "shrine", "castle"}
    words = en.split()
    if any(w.lower() in COMMON for w in words):
        return False
    if not (1 <= len(words) <= 3) or not all(w.isalpha() and w[:1].isupper() for w in words):
        return False
    # ฝั่งไทยต้องไม่มีเครื่องหมายวรรคตอนท้ายประโยค และมีคำไม่เกินจำนวนคำของ EN
    if any(c in th for c in "?!.…ๆ"):
        return False
    return len(th.split()) <= len(words)


