# คำไทย/ชื่อเฉพาะที่มีคำยืมสมัยใหม่เป็นซับสตริงโดยบังเอิญ — ต้องตัดออกก่อนตรวจ
# ตระกูล "บอส": ระดับ**อสูร** · กับ**อสูร** (…บ + อสูร) — วัดแล้ว 8 จุดในคลัง ไม่มีจุดไหนเป็นคำยืมจริง
# ตระกูล "เคส": **เคสุ**เกะ (ชื่อคน) · ตระกูล "โอเค": **โอเคฮาซามะ** (ชื่อโชกุนในมุก)
LOAN_FALSE_HITS = re.compile(
    r"โกลเวอร์|ทีมัน|ทีเดียว|ดีล่ะ|ดีละ|ดีลง|ยินดีลอง|มินิเกม|เกมส์กระดาน|หยุดเกม"
    r"|บอสูร|เคสุ|โอเคฮาซามะ|ดีลด"
)


def modern_loanwords(th):
    """คำยืมสมัยใหม่ที่พบจริงในบทพูดยุคเก่า — ตัดคำไทยปกติที่ซับสตริงไปชนออกก่อน

    ⚠ ต้องตัดซ้ำจนนิ่ง: การตัดรอบเดียวทำให้ตัวอักษรสองฝั่งมาชนกันเป็นคำยืมใหม่ได้
    (`สภาพดีทีเดียวล่ะ` -> ตัด `ทีเดียว` -> `สภาพดีล่ะ` -> ชนคำยืม `ดีล`
     ทั้งที่ `ดีล่ะ` อยู่ในบัญชีบวกปลอมอยู่แล้ว — ผู้ตรวจคลื่น MSG_073–075 รายงาน 3 ก.ย. 2026)
    """
    probe = th or ""
    for _ in range(5):                      # พอสำหรับการซ้อนกันจริงที่พบ (สูงสุด 2 ชั้น)
        stripped = LOAN_FALSE_HITS.sub("", probe)
        if stripped == probe:
            break
        probe = stripped
    return [w for w in MODERN_LOANWORDS if w in probe]
