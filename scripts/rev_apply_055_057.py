import sys, json

sys.stdout.reconfigure(encoding="utf-8")
sys.stderr.reconfigure(encoding="utf-8")

D = "translations/done"

EDITS = {
    "MSG_055": [
        ("แล้วประทาน 'คุณธรรม' ให้แน่นอน", "แล้วประทานคุณธรรมให้แน่นอน"),
        ("...'คุณธรรม' หรือ?", "...คุณธรรมหรือ?"),
        ("จะสรรเสริญและประทาน 'คุณธรรม' ให้", "จะสรรเสริญและประทานคุณธรรมให้"),
        ("จะสั่งสม 'คุณธรรม' มากแค่ไหนก็ได้", "จะสั่งสมคุณธรรมมากแค่ไหนก็ได้"),
        ("ผู้ที่สั่งสม 'คุณธรรม' ไว้ได้มาก", "ผู้ที่สั่งสมคุณธรรมไว้ได้มาก"),
        ("นั่นแหละคือ 'คุณธรรม'!", "นั่นแหละคือคุณธรรม!"),
        ("มีวิธีสั่งสม 'คุณธรรม' ทีละมาก ๆ", "มีวิธีสั่งสมคุณธรรมทีละมาก ๆ"),
        ("การทำภารกิจใน 'ใบประกาศความพากเพียร' ให้สำเร็จไง!",
         "การทำภารกิจในใบประกาศความพากเพียรให้สำเร็จไง!"),
        ("'ใบประกาศความพากเพียร' หรือ?", "ใบประกาศความพากเพียรหรือ?"),
        ("ใช่ 'ใบประกาศความพากเพียร' เป็นเอกสาร", "ใช่ ใบประกาศความพากเพียรเป็นเอกสาร"),
        ("ก็จะได้รับ 'คุณธรรม' เป็นกอบเป็นกำ", "ก็จะได้รับคุณธรรมเป็นกอบเป็นกำ"),
    ],
    "MSG_056": [
        ("ทนความร้อนแรงไม่ไหวแล้วหรือ?", "ทนแรงกดดันไม่ไหวเสียแล้วหรือ?"),
    ],
}

for b, rules in EDITS.items():
    p = f"{D}/batch_{b}.done.json"
    d = json.load(open(p, encoding="utf-8"))
    order = list(d["strings"])
    n_before = len(order)
    changed = []
    for old, new in rules:
        hit = 0
        for k in order:
            v = d["strings"][k]
            if old in v:
                d["strings"][k] = v.replace(old, new)
                changed.append((k, v, d["strings"][k]))
                hit += 1
        if hit != 1:
            raise SystemExit(f"[{b}] กฎ {old!r} จับได้ {hit} คีย์ (ต้องได้ 1)")
    assert list(d["strings"]) == order, "ลำดับคีย์เพี้ยน"
    assert len(d["strings"]) == n_before == 250, "จำนวนคีย์เพี้ยน"
    # ห้ามเหลืออัญประกาศของสองคำนี้
    for k in order:
        assert "'คุณธรรม'" not in d["strings"][k]
        assert "'ใบประกาศความพากเพียร'" not in d["strings"][k]
    with open(p, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{b}: แก้ {len(changed)} คีย์ · คีย์ทั้งหมด {len(d['strings'])}")
    for k, o, nv in changed:
        print(f"   คีย์: {k[:78]}")
        print(f"    เดิม: {o[:140]}")
        print(f"    ใหม่: {nv[:140]}")
