def main():
    fails = 0
    for text, should_fail, why in CASES:
        probs = check_text(text)
        ok = bool(probs) == should_fail
        fails += not ok
        print("%s  %-40s %s" % ("PASS" if ok else "FAIL", text, why if ok else probs))
    print()
    print("ผ่าน %d / %d" % (len(CASES) - fails, len(CASES)))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
