# การกวาดทำให้ตัวอย่างคำผิดกลายเป็นคำถูก จนบรรทัดอ่านไม่รู้เรื่อง (ผู้ตรวจ batch_117 เจอ)
SKIP = {"slotmap.json", "master_th.json", "glossary.md"}   # ไฟล์ที่สร้างด้วยเครื่อง/มีตัวอย่างคำผิด ห้ามกวาด


def targets(only=None):
    if only:
        return [paths.PROJECT / only]
    out = list(TARGET_FILES)
    for d in TARGET_DIRS:
        if not d.exists():
            continue
        for root, _dirs, files in os.walk(d):
            for f in files:
                # ข้ามรายงานผู้ตรวจ — เป็นเอกสารที่ "ยกคำผิดมาอ้าง" โดยตั้งใจ ถ้ากวาดจะลบหลักฐานทิ้ง
                if "review" in os.path.normpath(root).split(os.sep):
                    continue
                if os.path.splitext(f)[1] in EXTS and f not in SKIP:
                    out.append(paths.Path(root) / f)
    return [p for p in out if p.exists()]


def apply_rules(text):
    """คืน (ข้อความที่แก้แล้ว, [(bad, good, จำนวนที่เจอ)])"""
    hits = []
    for bad, good, _src in RULES:
        if bad.startswith("re:"):
            n = len(re.findall(bad[3:], text))
            if n:
                hits.append((bad, good, n))
                text = re.sub(bad[3:], good, text)
        elif bad in text:
            hits.append((bad, good, text.count(bad)))
            text = text.replace(bad, good)
    return text, hits


def report(p, hits):
    print("%-55s %s" % (p.relative_to(paths.PROJECT),
                        " · ".join("%s->%s x%d" % h for h in hits)))
    return sum(h[2] for h in hits)


def is_batch_json(p):
    """ไฟล์ worklist/done ที่มีโครง {priority, source_bins, strings, ref_tm}"""
    return (p.suffix == ".json" and p.name.startswith("batch_")
            and p.parent.name in ("done", "worklist"))


def scan_batch_json(p, write):
    """⚠ สแกน **เฉพาะช่อง `strings`** ของไฟล์ batch

    เพิ่ม 26 ส.ค. 2026 (sprint 15 · นักแปล batch_127 และ batch_129 รายงานตรงกัน):
    รูปเดิมอ่านไฟล์เป็น raw text ทั้งก้อน จึงนับคำผิดที่อยู่ใน **`ref_tm`** (ข้อมูลอ้างอิงจาก
    ภาคอื่น ซึ่งกติกาบอกว่า **ห้ามแตะ**) มาเป็นหนี้ของนักแปล — นักแปลสองคนใน sprint เดียว
    เสียเวลาไล่หาแล้วสรุปเองว่า "แก้ไม่ได้" ทั้งที่ไม่ใช่ความผิดของเขา
    ที่แย่กว่านั้น: ถ้ารัน `--write` รูปเดิมจะ **เขียนทับ `ref_tm` และไฟล์ต้นฉบับใน `worklist/`
    จริง ๆ** = แก้ข้อมูลนำเข้าโดยไม่มีใครรู้
    """
    with io.open(p, encoding="utf-8") as f:
        data = json.load(f)
    strings = data.get("strings")
    if not isinstance(strings, dict):
        return scan_raw(p, write)
    hits = collections.Counter()
    changed = False
    for k, v in list(strings.items()):
        if not isinstance(v, str):
            continue
        new, found = apply_rules(v)
        for bad, good, n in found:
            hits[(bad, good)] += n
        if new != v:
            strings[k] = new
            changed = True
    if not hits:
        return 0
    total = report(p, [(bad, good, n) for (bad, good), n in hits.items()])
    if write and changed:
        with io.open(p, "w", encoding="utf-8", newline="\n") as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write("\n")
    return total


def scan_raw(p, write):
    text = io.open(p, encoding="utf-8").read()
    new, hits = apply_rules(text)
    if not hits:
        return 0
    total = report(p, hits)
    if write:
        io.open(p, "w", encoding="utf-8", newline="\n").write(new)
    return total


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--only", help="แก้ไฟล์เดียว (path จากรากโปรเจกต์)")
    a = ap.parse_args()

    total = 0
    for p in targets(a.only):
        total += (scan_batch_json(p, a.write) if is_batch_json(p)
                  else scan_raw(p, a.write))

    print()
    print("รวม %d จุด%s" % (total, " (แก้แล้ว)" if a.write else " (ยังไม่แก้ — ใส่ --write)"))
    if not a.write and total:
        print("ที่มาของคำล็อก:")
        for bad, good, src in RULES:
            print("  %s -> %s   %s" % (bad, good, src))
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
