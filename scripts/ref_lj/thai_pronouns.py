# เป็นสรรพนาม จนนักแปล batch_127 ต้องเลี่ยงคำจนภาษาแข็ง (21 ส.ค. 2026)
# เพิ่ม 26 ส.ค. 2026 (sprint 12 · นักแปล batch_090 รายงาน): ฉากคุยเรื่อง**สีผม**ทำให้รูปเดิม
# จับผิดสามแบบที่ยังไม่ถูกกัน — `สีผมนี้` · `ผมของฉัน` · `ผมตัวเอง`
# ทั้งสามบรรทัดตก `merge_qc` ด่าน P จริง ๆ (ไม่ได้แค่เตือน) จนคำแปลที่ถูกต้องเข้า master ไม่ได้
# → เติม lookbehind `สี`/`ย้อม`/`หวี`/`เกล้า` และ lookahead `ของ`/`ตัวเอง`/`ร่วง`/`หงอก`/`นุ่ม`/`บาง`
# ⚠ `(?!ของ)` ปลอดภัยกับ "ผมขอ..." เพราะ "ขอ" ไม่มี ง ปิดท้าย จึงไม่เข้า lookahead
RE_PHOM = re.compile(r"(?<!เส้น)(?<!วิก)(?<!ทรง)(?<!ตัด)(?<!สระ)(?<!สี)(?<!ย้อม)(?<!หวี)(?<!เกล้า)"
                     r"ผม(?!เผ้า|ดำ|ขาว|ทอง|สี|ยาว|สั้น|หยิก|ตรง|ทรง|บลอนด์|ฟู|ซอย|ม้า"
                     # เพิ่มสีผมที่เหลือ 26 ส.ค. 2026 — รูปเดิมของ `check_pronoun_pairs.py`
                     # ไม่มีสีเหล่านี้ พอเอามาใช้เป็น POLITE ของตัวตรวจทะเบียนก็จับ "ไอ้ผอมผมแดง"
                     # (บทของเท็ตโซ T3 ใน batch_014) เป็นสรรพนาม "ผม" ทันที
                     r"|แดง|น้ำตาล|เทา|ม่วง|ชมพู|ฟ้า|เขียว|เงิน|ประบ่า|ปรก"
                     r"|ของ|ตัวเอง|ร่วง|หงอก|นุ่ม|บาง|เปีย|มัด)")
# ⚠ เพิ่ม `ร์` 27 ส.ค. 2026 (sprint 16) — คำว่า **"ปาร์กูร์" (Parkour)** มี "กู" อยู่ข้างใน
#   ทำให้ merge_qc ด่าน P **ตีกลับทั้ง batch 137** และเคยทำให้นักแปล batch 131 ต้องเขียนประโยคใหม่
#   เลี่ยงตัวตรวจโดยไม่จำเป็น · "กูร์" ไม่มีทางเป็นสรรพนามได้เพราะ `์` ปิดเสียงท้าย
# ⚠ เพิ่ม `โดะ` 28 ส.ค. 2026 (sprint 25) — ชื่อนักซิ่ง **"กูโดะ" (Gudo)** ที่ master ship ไว้แล้ว มี "กู" อยู่ข้างใน
#   ทำให้ด่าน P / check_character_register เตือนเท็จทุกบรรทัดของตัวละครนี้ (เพศ unknown จึงต้องแปลกลางเพศ)
RE_KU = re.compile(r"(?<!ยา)(?<!ตระ)(?<!สุด)(?<!โอ)(?<!ซา)"
                   r"กู(?!เกิล|รู(?!้)|ซ่า|ล|้|่|จิ|ดะ|โดะ|ไร|ร์)")

# ── คำเรียกคู่สนทนา ────────────────────────────────────────────────────────
# กัน ขอบคุณ/บุญคุณ/คุณภาพ + คำเรียกญาติที่ขึ้นต้นด้วย "คุณ" ซึ่งเป็นคำนามเรียกบุคคลที่สาม
RE_KHUN = re.compile(r"(?<!ขอบ)(?<!บุญ)(?<!เนร)คุณ(?!ภาพ|สมบัติ|ค่า|ธรรม|ประโยชน์|วุฒิ|งาม|หมอ"
                     r"|ยาย|ย่า|ปู่|ตา|น้า|ลุง|ป้า|พ่อ|แม่|นาย)")
# ⚠ `ก` ในลิสต์กันคำว่า "นายก" (รัฐมนตรี) แต่เดิมกันกว้างเกินไปจนพลาด **"นายก็" และ "นายกับ"**
# ซึ่งเป็น "นาย" + คำถัดไป — เจอ 26 ส.ค. 2026 (sprint 12 · ผู้ตรวจ batch_097 ไล่ทีละบรรทัด
# แล้วพบว่าตัวตรวจข้าม 11 บรรทัดที่ไคโตะเรียกผู้หญิงว่า "นาย")
# → กลับด้านเป็น `ก(?=[รฯ]|สมาคม|สภา|\s|$)` : กันเฉพาะรูปที่เป็น "นายก" จริง ๆ
#   ("นายกรัฐมนตรี" · "นายกฯ" · "นายกสมาคม" · "นายก" ลอย ๆ) ส่วน "นายก็/นายกับ/นายกำลัง/
#   นายกลัว" ซึ่งเป็น "นาย" + คำถัดไป จับได้หมด (รูปก่อนหน้าที่ใช้ `ก(?![็ั])` ยังพลาดสองแบบหลัง)
# ⚠ `(?<!ทำ)` ยังกัน "ทำนาย" (พยากรณ์) ซึ่งพ้องรูปกับ "ทำ + นาย" (ทำให้นายลำบาก) แบบแยกไม่ออก
#   ด้วย regex — กรณีนี้ต้องพึ่งผู้ตรวจอ่านเอง
RE_NAI = re.compile(r"(?<!ท)(?<!ทำ)(?<!คุณ)(?<!เจ้า)(?<!หัวหน้า)"
                    r"นาย(?!ของ|จ้าง|ก(?=[รฯ]|สมาคม|สภา|\s|$)|ทุน|หน้า|ท่าน|ตำรวจ|แพทย์|ธนาคาร|อำเภอ|พล|เรือ|"
                    r"สถานี|ประกัน|ทะเบียน)")
# ⚠ รูปเดิมกันคำอื่นด้วยการ "ห้ามตามด้วยพยัญชนะ" ทั้งชุด `[งะ้ลนมวำจิีุ๊๋็่]` ซึ่ง **กว้างเกินไป**
# จนพลาดคำเรียกคู่สนทนาของจริงไปเยอะมาก — วัดกับ master_th (26 ส.ค. 2026 · sprint 11) พบว่า
# จับได้ 171 จุด แต่ **ไม่จับ** อีก 760 จุด ซึ่งในนั้นมีของจริงปนอยู่หลายสิบ:
#   แกนี่ · แกจะ · แกนั่น · แกมัน · แกที่ · แกกัน · แกใคร · แกน่า · แกคนเดียว · แกว่า
