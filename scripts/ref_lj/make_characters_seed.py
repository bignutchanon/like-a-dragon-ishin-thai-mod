CHAP_RE = re.compile(r"^\d+$")


def load(p, default=None):
    if not os.path.exists(p):
        return default
    return json.load(io.open(p, encoding="utf-8"), object_pairs_hook=collections.OrderedDict)


def gather_samples(max_n=3):
    """คืน ({ผู้พูด: [บทพูด EN]}, {ผู้พูด: set(บทที่)}) จาก sound_auth + talk"""
    samples = collections.defaultdict(list)
    chapters = collections.defaultdict(set)
    sm = load(SPEECH, {}) or {}
    for text, rec in sm.items():
        toks = list(rec.get("speaker_exact") or []) or list(rec.get("speaker") or [])
        for t in toks:
            if len(samples[t]) < max_n and 10 < len(text) < 160:
                samples[t].append(text)
            for c in rec.get("chapter", []):
                if CHAP_RE.match(str(c)):
                    chapters[t].add(int(c))
    ts = load(TALK, {}) or {}
    for text, rec in ts.items():
        n = (rec.get("speaker") or "").strip()
        if n and len(samples[n]) < max_n and 10 < len(text) < 160:
            samples[n].append(text)
    return samples, chapters


def evidence_roles():
    """{นามสกุล/ชื่อ (lower): คำอธิบายบทบาทจากแฟ้มคดีในเกม}

    `evidence.bin` เขียนไว้ว่าใครเป็นใครในคดี — เอามาเติมช่อง role ให้ทีมแปลได้เลย
    (สร้างด้วย scripts/make_story_context.py)
    """
    p = FACTS / "evidence.json"
    if not os.path.exists(p):
        return {}
    data = load(p, {}) or {}
    out = {}
    for rows in data.values():
        for r in rows:
            nm, desc = (r.get("name") or "").strip(), (r.get("desc") or "").strip()
            if not nm or not desc or len(desc) < 15:
                continue
            clean = re.sub(r"\s*\(.*?\)", "", nm).strip()
            entry = "%s — %s" % (nm, desc)
            for token in {clean, clean.split()[-1] if clean.split() else ""}:
                k = token.lower()
                if not k or len(k) <= 2:
                    continue
                # นามสกุลเดียวกันมีได้หลายคน (Ehara พ่อ/ลูก) — เก็บทุกคนไว้ให้คนแปลเลือกเอง
                lst = out.setdefault(k, [])
                if entry not in lst and len(lst) < 3:
                    lst.append(entry)
    return out


